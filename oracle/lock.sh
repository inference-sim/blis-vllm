#!/bin/bash
# Original to blis-vllm.
# Write the oracle's hash-locked install files from oracle/requirements.lock (X21).
#
# oracle/requirements.lock is the oracle's environment, every package pinned; each trace records
# its sha256 (provenance requirements_lock_sha256), so it is not rewritten here. This resolves
# exactly those pins again, with uv pip compile (pip-compile's resolver) and --generate-hashes,
# for CPython 3.12 on Linux x86_64, the platform CI runs, and writes:
#
#   oracle/requirements-hashed.txt  the same packages, each with the sha256 of every archive
#   oracle/requirements-pip.txt     the pip release CI upgrades to first, with its hashes
#
# CI installs both with pip install --require-hashes, so an archive that changed fails the
# install. oracle/check_lock.py --hashed checks that requirements-hashed.txt pins exactly what
# requirements.lock pins.
#
#   oracle/lock.sh           write both files
#   oracle/lock.sh --check   fail if either differs from what this would write
set -euo pipefail
cd "$(dirname "$0")"
pip_release="26.2.2"
check=false
[ "${1:-}" = "--check" ] && check=true
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
grep -v '^#' requirements.lock > "$tmp/requirements.in"
echo "pip==$pip_release" > "$tmp/pip.in"
compile() {
  (cd "$tmp" && uv pip compile --quiet --generate-hashes --no-header --no-annotate \
    --python-version 3.12 --python-platform x86_64-unknown-linux-gnu \
    --extra-index-url https://download.pytorch.org/whl/cpu --index-strategy unsafe-best-match "$1")
}
{
  echo "# Generated from requirements.lock by oracle/lock.sh for CPython 3.12 on Linux x86_64; do not edit."
  echo "# Install with: pip install --require-hashes --no-deps --extra-index-url https://download.pytorch.org/whl/cpu -r oracle/requirements-hashed.txt"
  compile requirements.in
} > "$tmp/requirements-hashed.txt"
{
  echo "# Generated by oracle/lock.sh; do not edit."
  echo "# Install with: python -m pip install --require-hashes -r oracle/requirements-pip.txt"
  compile pip.in
} > "$tmp/requirements-pip.txt"
status=0
for f in requirements-hashed.txt requirements-pip.txt; do
  if $check; then
    cmp -s "$tmp/$f" "$f" || { echo "oracle/$f differs from what oracle/lock.sh writes" >&2; status=1; }
  else
    cp "$tmp/$f" "$f"
  fi
done
exit $status
